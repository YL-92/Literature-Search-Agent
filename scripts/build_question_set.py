def build(output: Path) -> None:
    """Write the ordered JSONL question set."""
    rows = []
    index = 1
    for category, queries in QUESTIONS.items():
        for offset, query in enumerate(queries):
            difficulty = "easy" if offset < 3 else "medium" if offset < 8 else "hard"
            rows.append(
                {
                    "question_id": f"Q{index:03d}",
                    "category": category,
                    "query": query,
                    "expected_answer_type": (
                        "comparison"
                        if "比较" in query or "差异" in query
                        else "evaluation"
                        if "评估" in query or "指标" in query or "基准" in query
                        else "method"
                    ),
                    "citation_requirement": "每个事实、比较结论和数字都必须绑定可核验论文来源",
                    "difficulty": difficulty,
                }
            )
            index += 1
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        "\n".join(json.dumps(row, ensure_ascii=False) for row in rows) + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    build(Path(__file__).resolve().parents[1] / "data" / "test_questions.jsonl")
